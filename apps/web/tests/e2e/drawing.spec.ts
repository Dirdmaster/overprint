import { test, expect } from '@playwright/test'
import { demoBoard } from '../fixtures/demoBoard'

test('draw, edit, undo and reload a rounded rectangle without losing geometry', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await page.getByRole('button', { name: 'Draw rounded rectangle', exact: true }).click()
  const canvas = page.locator('svg[role="img"]')
  const box = await canvas.evaluate(svg => {
    const group = svg.querySelector('g[transform]') as SVGGraphicsElement
    const point = new DOMPoint(30, 50).matrixTransform(group.getScreenCTM()!)
    return { x: point.x - 220, y: point.y - 200 }
  })
  await page.mouse.move(box.x + 220, box.y + 200)
  await page.mouse.down()
  await page.mouse.move(box.x + 320, box.y + 260)
  await expect(page.locator('[data-drawing-preview]')).toBeVisible()
  await page.mouse.up()
  await expect(page.locator('[data-artwork-layer] image')).toHaveCount(1)
  await page.getByLabel('Shape width (mm)', { exact: true }).fill('12')
  await page.getByLabel('Shape width (mm)', { exact: true }).press('Tab')
  await page.getByLabel('Corner radius (mm)').fill('2')
  await page.getByLabel('Corner radius (mm)').press('Tab')
  const source = decodeURIComponent((await page.locator('[data-artwork-layer] image').getAttribute('href'))!)
  expect(source).toContain('width="12"')
  expect(source).toContain('rx="2"')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Corner radius (mm)')).not.toHaveValue('2')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.getByLabel('Corner radius (mm)')).toHaveValue('2')
  await page.screenshot({ path: 'test-results/drawing-shapes-desktop.png' })
  await page.keyboard.press('Control+s')
  await expect(page.getByRole('status')).toContainText('All changes saved')
  await page.reload()
  await page.getByRole('button', { name: 'Rounded rectangle', exact: true }).click()
  await expect(page.getByLabel('Corner radius (mm)')).toHaveValue('2')
  await page.getByRole('button', { name: 'Draw ellipse', exact: true }).click()
  await page.mouse.move(box.x + 220, box.y + 200)
  await page.mouse.down()
  await page.mouse.move(box.x + 300, box.y + 260)
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await expect(page.locator('[data-artwork-layer] image')).toHaveCount(1)
})

test('drawing on the back uses the same positive bounds and requires conversion before Live Paint', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await page.getByRole('button', { name: 'Draw rectangle', exact: true }).click()
  const point = await page.locator('svg[role="img"]').evaluate(svg => {
    const group = svg.querySelector('g[transform]') as SVGGraphicsElement
    const first = new DOMPoint(30, 50).matrixTransform(group.getScreenCTM()!)
    const last = new DOMPoint(38, 58).matrixTransform(group.getScreenCTM()!)
    return { x: first.x, y: first.y, xx: last.x, yy: last.y }
  })
  await page.mouse.move(point.x, point.y)
  await page.mouse.down()
  await page.mouse.move(point.xx, point.yy)
  await page.mouse.up()
  await page.getByRole('button', { name: 'Live paint (K)' }).click()
  await page.mouse.click((point.x + point.xx) / 2, (point.y + point.yy) / 2)
  await expect(page.getByRole('alert')).toContainText('Convert this editable shape')
  await expect(page.getByLabel('Shape width (mm)', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Convert to SVG', exact: true }).click()
  await expect(page.getByLabel('Shape width (mm)', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Shape width (mm)', { exact: true })).toBeVisible()
})
