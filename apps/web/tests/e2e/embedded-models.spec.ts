import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'
for (const name of ['embedded-models', 'embedded-mixed']) test(`imports ${name} locally, renders both sides and restores a downloaded project`, async ({ page }) => {
  const uploads: string[] = [], errors: string[] = []
  page.on('request', request => { if (request.method() !== 'GET') uploads.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(`tests/fixtures/${name}.kicad_pcb`)
  await expect(page.getByRole('button', { name: '3D', exact: true })).toBeEnabled({ timeout: 45000 })
  await page.getByRole('button', { name: '3D', exact: true }).click()
  await expect(page.getByText(/Drag to orbit/)).toBeVisible()
  const canvas = page.getByRole('img', { name: `${name} assembled 3D preview` })
  await expect(canvas).toBeVisible()
  await page.screenshot({ path: `test-results/${name}-front.png` })
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await page.screenshot({ path: `test-results/${name}-back.png` })
  await page.keyboard.press('ControlOrMeta+s')
  await expect(page.getByRole('status')).toContainText('All changes saved')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Save project', exact: true }).click()
  const saved = (await (await download).path())!
  const project = JSON.parse(readFileSync(saved, 'utf8'))
  expect(project.board.models.includedReferences).toEqual(['U1', 'U2'])
  await page.reload()
  await expect(page.getByRole('button', { name: '3D', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Open project', exact: true }).click()
  await page.getByLabel('Choose project file').setInputFiles({ name: 'embedded.overprint', mimeType: 'application/json', buffer: readFileSync(saved) })
  await expect(page.getByRole('button', { name: '3D', exact: true })).toBeEnabled()
  expect(uploads).toEqual([])
  expect(errors).toEqual([])
})

test('refreshes an embedded PCB while keeping existing artwork', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles('tests/fixtures/embedded-mixed.kicad_pcb')
  await expect(page.getByRole('button', { name: '3D', exact: true })).toBeEnabled({ timeout: 45000 })
  await page.getByLabel('Choose SVG graphic').setInputFiles('tests/fixtures/class-paints.svg')
  await expect(page.locator('[data-artwork-layer] image')).toHaveCount(1)
  await page.getByLabel('More ways to open a board').click()
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles('tests/fixtures/embedded-models.kicad_pcb')
  await page.getByRole('button', { name: 'Update PCB, keep artwork', exact: true }).click({ timeout: 5000 })
  await expect(page.locator('[data-artwork-layer] image')).toHaveCount(1)
  await expect(page.getByRole('img', { name: 'embedded-models front board preview' })).toBeVisible()
  await expect(page.getByRole('button', { name: '3D', exact: true })).toBeEnabled()
})
