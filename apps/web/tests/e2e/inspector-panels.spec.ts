import { test, expect } from '@playwright/test'
import { demoBoard } from '../fixtures/demoBoard'
const open = async (page: import('@playwright/test').Page) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
}
test('inspector separates layers, color, layout and board while retaining selection and global undo', async ({ page }) => {
  await open(page)
  await page.getByLabel('Choose SVG graphic').setInputFiles({ name: 'Mark.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"><path d="M0 0H10V10Z" fill="#ffd426"/></svg>') })
  await expect(page.getByRole('tab', { name: 'Layers', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('region', { name: 'Front artboard layers', exact: true })).toBeVisible()
  await expect(page.getByText('Smart placement', { exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Color', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Fill colors', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Change fill #ffd426', exact: true })).toBeEnabled()
  await expect(page.getByRole('region', { name: 'Front artboard layers', exact: true })).not.toBeVisible()
  await page.getByRole('tab', { name: 'Layout', exact: true }).click()
  const layout = page.getByRole('region', { name: 'Layout tools', exact: true })
  await layout.getByRole('button', { name: 'Preview repeat', exact: true }).click()
  await expect(page.locator('[data-repeat-preview]')).toHaveCount(2)
  await page.getByRole('tab', { name: 'Color', exact: true }).click()
  await page.getByRole('tab', { name: 'Layout', exact: true }).click()
  await expect(page.locator('[data-repeat-preview]')).toHaveCount(2)
  await layout.getByRole('button', { name: 'Apply repeat', exact: true }).click()
  await expect(page.locator('[data-artwork-layer] image')).toHaveCount(3)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('[data-artwork-layer] image')).toHaveCount(1)
  await layout.getByLabel('Repeat mode', { exact: true }).selectOption('circle')
  await expect(layout.getByLabel('Repeat radius', { exact: true })).toBeVisible()
  await expect(layout.getByLabel('Repeat X spacing', { exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Board', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Print checks', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Review PCB file update', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Layers', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Layer name', exact: true })).toHaveValue('Mark.svg')
})
test('inspector tabs support keyboard navigation and compact mobile controls', async ({ page }, testInfo) => {
  await open(page)
  const layers = page.getByRole('tab', { name: 'Layers', exact: true })
  await layers.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Color', exact: true })).toBeFocused()
  await page.keyboard.press('End')
  await expect(page.getByRole('tab', { name: 'Board', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Home')
  await expect(layers).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  const navigation = page.getByRole('tablist', { name: 'Inspector panels', exact: true })
  await navigation.scrollIntoViewIfNeeded()
  expect((await navigation.boundingBox())!.width).toBeLessThanOrEqual(390)
  await page.getByRole('tab', { name: 'Layout', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Preview repeat', exact: true })).toBeDisabled()
  await expect(page.getByRole('heading', { name: 'Repeat artwork', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: testInfo.outputPath('inspector-mobile.png'), fullPage: true })
})
