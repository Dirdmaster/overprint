for (const key of ['Backspace', 'Delete']) {
  test(`${key} removes the selected image and undo restores it`, async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
    await page.getByLabel('Choose board export').setInputFiles(fixture)
    await page.getByLabel('Choose SVG graphic').setInputFiles(graphic)
    await page.getByRole('button', { name: 'red-square.svg', exact: true }).click()
    await page.keyboard.press(key)
    await expect(page.locator('[data-artwork-layer] image')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'red-square.svg', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(page.locator('[data-artwork-layer] image')).toHaveCount(1)
    // Text editing must not delete the selected graphic.
    await page.getByRole('button', { name: 'red-square.svg', exact: true }).click()
    await page.getByLabel('Layer name', { exact: true }).focus()
    await page.keyboard.press(key)
    await expect(page.locator('[data-artwork-layer] image')).toHaveCount(1)
    await page.getByRole('button', { name: 'Delete red-square.svg', exact: true }).click()
    await expect(page.locator('[data-artwork-layer] image')).toHaveCount(0)
  })
}
