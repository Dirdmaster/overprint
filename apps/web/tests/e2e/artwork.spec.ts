for (const side of ['Front', 'Back']) test(`resizing rotated ${side.toLowerCase()} artwork keeps its opposite handle anchored`, async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(fixture)
  await page.getByRole('button', { name: side, exact: true }).click()
  await page.getByLabel('Choose SVG graphic').setInputFiles(graphic)
  const width = page.getByLabel('Artwork width', { exact: true })
  const rotation = page.getByLabel('Artwork rotation', { exact: true })
  await rotation.fill('30'); await rotation.press('Tab')
  const oldWidth = Number(await width.inputValue())
  const anchor = page.getByLabel('Resize artwork: top left', { exact: true })
  const a = (await anchor.boundingBox())!
  const handle = page.getByLabel('Resize artwork', { exact: true })
  const b = (await handle.boundingBox())!
  const ax = a.x + a.width / 2, ay = a.y + a.height / 2
  const bx = b.x + b.width / 2, by = b.y + b.height / 2
  await page.mouse.move(bx, by)
  await page.mouse.down()
  await page.mouse.move(bx + (bx - ax) * 0.2, by + (by - ay) * 0.2, { steps: 4 })
  await page.mouse.up()
  expect(Number(await width.inputValue())).toBeCloseTo(oldWidth * 1.2, 1)
  const after = (await anchor.boundingBox())!
  expect(after.x + after.width / 2).toBeCloseTo(ax, 0)
  expect(after.y + after.height / 2).toBeCloseTo(ay, 0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  expect(Number(await width.inputValue())).toBeCloseTo(oldWidth, 2)
  await expect(rotation).toHaveValue('30')
  const image = page.locator('[data-artwork-layer] image').first()
  const imageBefore = (await image.boundingBox())!
  const centered = (await handle.boundingBox())!
  await page.keyboard.down('Alt')
  await page.mouse.move(centered.x + centered.width / 2, centered.y + centered.height / 2)
  await page.mouse.down()
  await page.mouse.move(centered.x + centered.width / 2 + (bx - ax) * 0.1, centered.y + centered.height / 2 + (by - ay) * 0.1)
  await page.mouse.up(); await page.keyboard.up('Alt')
  const imageAfter = (await image.boundingBox())!
  expect(imageAfter.x + imageAfter.width / 2).toBeCloseTo(imageBefore.x + imageBefore.width / 2, 0)
  expect(imageAfter.y + imageAfter.height / 2).toBeCloseTo(imageBefore.y + imageBefore.height / 2, 0)
  expect(Number(await width.inputValue())).toBeGreaterThan(oldWidth)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  // Modifier rotation stays on a predictable angular increment.
  const r = (await page.getByLabel('Rotate artwork', { exact: true }).boundingBox())!
  await page.keyboard.down('Shift')
  await page.mouse.move(r.x + r.width / 2, r.y + r.height / 2)
  await page.mouse.down(); await page.mouse.move(r.x + 40, r.y + 30, { steps: 4 }); await page.mouse.up()
  await page.keyboard.up('Shift')
  expect(Number(await rotation.inputValue()) % 15).toBe(0)
})
