test('project autosaves, downloads, and reopens with artwork intact', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(fixture)
  await page.getByLabel('Choose SVG graphic').setInputFiles(graphic)
  const handle = page.getByLabel('Resize artwork', { exact: true })
  const h = (await handle.boundingBox())!
  await page.mouse.move(h.x + h.width / 2, h.y + h.height / 2)
  await page.mouse.down(); await page.mouse.move(h.x + 25, h.y + 25); await page.mouse.up()
  const width = await page.getByLabel('Artwork width', { exact: true }).inputValue()
  expect(Number(width)).toBeGreaterThan(28)
  const rotate = (await page.getByLabel('Rotate artwork', { exact: true }).boundingBox())!
  await page.mouse.move(rotate.x + rotate.width / 2, rotate.y + rotate.height / 2)
  await page.mouse.down(); await page.mouse.move(rotate.x + 35, rotate.y + 20); await page.mouse.up()
  await expect(page.getByLabel('Artwork rotation')).not.toHaveValue('0')
  await page.getByLabel('Artwork rotation').fill('25'); await page.getByLabel('Artwork rotation').press('Tab')
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect.poll(() => page.evaluate(() => new Promise(resolve => {
    const request = indexedDB.open('overprint', 1)
    request.onsuccess = () => { const db = request.result; const read = db.transaction('projects').objectStore('projects').get('current'); read.onsuccess = () => { resolve(JSON.parse(read.result ?? '{}').side); db.close() } }
  }))).toBe('back')
  await page.reload()
  await expect(page.getByRole('img', { name: 'Demo board back board preview' })).toBeVisible()
  await page.getByRole('button', { name: 'Front', exact: true }).click()
  await page.getByRole('button', { name: 'red-square.svg', exact: true }).click()
  await expect(page.getByLabel('Artwork width', { exact: true })).toHaveValue(width)
  await expect(page.getByLabel('Artwork rotation')).toHaveValue('25')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Save project', exact: true }).click()
  const file = await download
  const path = await file.path()
  await page.getByRole('button', { name: 'Delete red-square.svg' }).click()
  await page.getByLabel('Choose project file').setInputFiles(path!)
  await expect(page.getByRole('button', { name: 'red-square.svg', exact: true })).toBeVisible()
  await page.keyboard.press('Control+s')
  await expect(page.getByRole('status')).toContainText('All changes saved')
})

