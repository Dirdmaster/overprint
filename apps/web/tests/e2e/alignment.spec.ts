test('overlapping distribution persists in downloads without changing hidden or rear artwork', async ({ page }) => {
  await open(page)
  await graphic(page, 'Hidden.svg', 15, 80, 5)
  await action(page, 'Toggle Hidden.svg')
  await action(page, 'Back')
  await graphic(page, 'Rear.svg', 40, 60, 5)
  await action(page, 'Front')
  await graphic(page, 'A.svg', 10, 30, 20)
  await graphic(page, 'B.svg', 22, 30, 20)
  await graphic(page, 'C.svg', 30, 30, 20)
  await select(page, ['A.svg', 'B.svg', 'C.svg'])
  await action(page, 'Distribute horizontal spacing')
  await expect.poll(() => positions(page)).toEqual([{ x: 10, y: 30 }, { x: 20, y: 30 }, { x: 30, y: 30 }])
  const downloadPromise = page.waitForEvent('download')
  await action(page, 'Save project')
  const file = await downloadPromise
  const { readFile } = await import('node:fs/promises')
  const project = JSON.parse(await readFile((await file.path())!, 'utf8'))
  expect(project.artwork.map((item: { name: string; x: number; y: number; side: string; visible: boolean }) => ({ name: item.name, x: item.x, y: item.y, side: item.side, visible: item.visible }))).toEqual([
    { name: 'Hidden.svg', x: 15, y: 80, side: 'front', visible: false },
    { name: 'Rear.svg', x: 40, y: 60, side: 'back', visible: true },
    { name: 'A.svg', x: 10, y: 30, side: 'front', visible: true },
    { name: 'B.svg', x: 20, y: 30, side: 'front', visible: true },
    { name: 'C.svg', x: 30, y: 30, side: 'front', visible: true },
  ])
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.getByRole('region', { name: 'Artwork alignment' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results/artwork-alignment-dark.png' })
})
