import { routeGeist } from '../fixtures/googleFontFixture'
import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { createHash } from 'node:crypto'
import { demoBoard } from '../fixtures/demoBoard'
// A synthetic catalogue backed by the licensed Inter test font, not a live Google family.
const require = createRequire(import.meta.url)
const converter = require('opentype.js')
const woff = readFileSync(new URL('../../../../node_modules/@fontsource/inter/files/inter-latin-700-normal.woff', import.meta.url))
const ttf = process.env.OVERPRINT_REAL_FONT_TTF ? readFileSync(process.env.OVERPRINT_REAL_FONT_TTF) : Buffer.from((() => { const font = converter.parse(woff.buffer.slice(woff.byteOffset, woff.byteOffset + woff.byteLength)); delete font.tables.gsub; delete font.tables.gpos; return font.toArrayBuffer() })())
const id = 'a'.repeat(64)
const family = { family: 'Fixture Sans', category: 'sans-serif', version: 'v1', variants: [{ variant: 'regular', id: 'b'.repeat(64) }, { variant: '700', id }] }

test('search, preview and apply a font; frozen text reopens offline and failed edits preserve outlines', async ({ page }) => {
  const queries: string[] = []
  let downloads = 0
  await page.route('**/api/fonts/catalog?*', route => {
    queries.push(new URL(route.request().url()).searchParams.get('q')!)
    return route.fulfill({ json: { families: [family], total: 1, offset: 0 } })
  })
  await page.route('**/api/fonts/file?*', route => { downloads++; return route.fulfill({ contentType: 'font/ttf', body: ttf }) })
  await routeGeist(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await page.getByRole('button', { name: 'Draw text', exact: true }).click()
  await page.getByRole('img', { name: 'Demo board front board preview' }).click()
  const image = page.locator('[data-artwork-layer] image')
  const before = await image.getAttribute('href')
  await page.getByRole('combobox', { name: 'Font family', exact: true }).click()
  await page.getByRole('combobox', { name: 'Search font families' }).fill('Fixture')
  await expect.poll(() => queries).toContain('Fixture')
  await expect(image).toHaveAttribute('href', before!)
  await page.getByRole('option', { name: 'Fixture Sans', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Font family', exact: true })).toContainText('Fixture Sans')
  await page.getByRole('combobox', { name: 'Font style', exact: true }).selectOption('700')
  await expect(image).not.toHaveAttribute('href', before!)
  await expect(page.getByText('Updating text…', { exact: true })).toHaveCount(0)
  const after = await image.getAttribute('href')
  const saving = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Save project', exact: true }).click()
  const saved = JSON.parse(readFileSync((await (await saving).path())!, 'utf8'))
  expect(saved.artwork[0].drawing.google).toMatchObject({ family: 'Fixture Sans', variant: '700', version: 'v1', id, sha256: createHash('sha256').update(ttf).digest('hex') })
  expect(saved.artwork[0].drawing.google.license).toBeTruthy()
  expect(saved.artwork[0].source).not.toContain('<text')
  // Explicitly upgrade, then Undo: cached newer styles must not follow the older identity.
  await page.route('**/api/fonts/catalog?*', route => route.fulfill({ json: { families: [{ ...family, version: 'v2', variants: [{ variant: '900', id: 'd'.repeat(64) }] }], total: 1, offset: 0 } }))
  await page.getByRole('combobox', { name: 'Font family', exact: true }).click()
  await page.getByRole('option', { name: 'Fixture Sans', exact: true }).click()
  await expect(page.getByLabel('Font style')).toHaveValue('900')
  await expect(page.getByText('Updating text…', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Font style')).toHaveValue('700')
  await expect(page.getByLabel('Font style').locator('option')).toHaveCount(1)
  await expect(image).toHaveAttribute('href', after!)

  await page.keyboard.press('Control+s')
  await expect(page.getByRole('status')).toContainText('All changes saved')
  await page.route('**/api/fonts/file?*', route => route.fulfill({ status: 503 }))
  await page.reload()
  await expect(image).toHaveAttribute('href', after!)
  expect(downloads).toBe(3)
  const exporting = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Save project', exact: true }).click()
  const reopened = JSON.parse(readFileSync((await (await exporting).path())!, 'utf8'))
  expect(reopened.artwork[0].source).toBe(saved.artwork[0].source)
  expect(reopened.artwork[0].drawing).toEqual(saved.artwork[0].drawing)
  await page.getByRole('button', { name: 'Text', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Font family', exact: true })).toContainText('Fixture Sans')
  // Browsing a newer catalogue must not silently offer unpinned replacement styles.
  await page.route('**/api/fonts/catalog?*', route => route.fulfill({ json: { families: [{ ...family, version: 'v2', variants: [{ variant: '900', id: 'd'.repeat(64) }] }], total: 1, offset: 0 } }))
  await page.getByRole('combobox', { name: 'Font family', exact: true }).click()
  await expect(page.getByRole('option', { name: 'Fixture Sans', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Font style').locator('option')).toHaveCount(1)
  await expect(page.getByLabel('Font style')).toHaveValue('700')
  await page.route('**/api/fonts/catalog?*', route => route.fulfill({ json: { families: [family], total: 1, offset: 0 } }))
  await page.getByLabel('Font style').focus()
  await expect(page.getByLabel('Font style').locator('option')).toHaveCount(2)
  await page.getByLabel('Text content').fill('Changed offline')
  await expect(page.getByRole('alert')).toContainText('Existing artwork still displays and exports')
  await expect(image).toHaveAttribute('href', after!)
  // A valid but different font under the same identity must not silently replace saved paths.
  const otherWoff = readFileSync(new URL('../../../../node_modules/@fontsource/inter/files/inter-latin-400-normal.woff', import.meta.url))
  const other = Buffer.from((() => { const font = converter.parse(otherWoff.buffer.slice(otherWoff.byteOffset, otherWoff.byteOffset + otherWoff.byteLength)); delete font.tables.gsub; delete font.tables.gpos; return font.toArrayBuffer() })())
  await page.route('**/api/fonts/file?*', route => route.fulfill({ contentType: 'font/ttf', body: other }))
  await page.reload()
  await page.getByRole('button', { name: 'Text', exact: true }).click()
  await page.getByLabel('Text content').fill('Changed bytes')
  await expect(page.getByRole('alert')).toContainText('Font bytes have changed')
  await expect(image).toHaveAttribute('href', after!)
  await page.getByRole('combobox', { name: 'Font family', exact: true }).click()
  await expect(page.getByRole('option', { name: 'Geist (offline)', exact: true })).toHaveCount(0)
  await page.getByRole('option', { name: 'Fixture Sans', exact: true }).click()
  await expect(image).not.toHaveAttribute('href', after!)
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(image).toHaveAttribute('href', after!)
  await expect(page.getByLabel('Text content')).toHaveValue('Text')
})

