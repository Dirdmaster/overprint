test('pending family download preserves artwork and cannot overwrite a newer text draft', async ({ page }) => {
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  let requested = false
  await page.route('**/api/fonts/catalog?*', route => route.fulfill({ json: { families: [family], total: 1, offset: 0 } }))
  await page.route('**/api/fonts/file?*', async route => { requested = true; await gate; await route.fulfill({ contentType: 'font/ttf', body: ttf }) })
  await routeGeist(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await page.getByRole('button', { name: 'Draw text', exact: true }).click()
  await page.getByRole('img', { name: 'Demo board front board preview' }).click()
  const image = page.locator('[data-artwork-layer] image')
  const before = await image.getAttribute('href')
  const trigger = page.getByRole('combobox', { name: 'Font family', exact: true })
  await trigger.click()
  await page.getByRole('option', { name: 'Fixture Sans' }).click()
  await expect.poll(() => requested).toBe(true)
  await expect(image).toHaveAttribute('href', before!)
  await expect(trigger).toContainText('Geist')
  await page.keyboard.press('Escape')
  await page.getByLabel('Text content').fill('Newer draft')
  await expect(image).not.toHaveAttribute('href', before!)
  const newer = await image.getAttribute('href')
  const completed = page.waitForResponse('**/api/fonts/file?*')
  release()
  await completed
  await expect(page.getByText('Loading font…', { exact: true })).toHaveCount(0)
  await expect(image).toHaveAttribute('href', newer!)
  await expect(trigger).toContainText('Geist')
})

test('a newer highlighted family previews after the bounded in-flight preview finishes', async ({ page }) => {
  const second = { ...family, family: 'Fixture Serif', variants: [{ variant: 'regular', id: 'e'.repeat(64) }] }
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const requested: string[] = []
  await page.route('**/api/fonts/catalog?*', route => route.fulfill({ json: { families: [family, second], total: 2, offset: 0 } }))
  await page.route('**/api/fonts/file?*', async route => {
    const name = new URL(route.request().url()).searchParams.get('family')!
    requested.push(name)
    if (name === family.family) await gate
    await route.fulfill({ contentType: 'font/ttf', body: ttf })
  })
  await routeGeist(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await page.getByRole('button', { name: 'Draw text', exact: true }).click()
  await page.getByRole('img', { name: 'Demo board front board preview' }).click()
  await page.getByRole('combobox', { name: 'Font family', exact: true }).click()
  await page.getByRole('option', { name: 'Fixture Sans', exact: true }).hover()
  await expect.poll(() => requested).toEqual(['Fixture Sans'])
  await page.getByRole('option', { name: 'Fixture Serif', exact: true }).hover()
  await expect(page.getByRole('option', { name: 'Fixture Serif', exact: true })).toHaveAttribute('data-highlighted', '')
  // Let the deliberate preview debounce expire while the first download remains held.
  await page.waitForTimeout(300)
  expect(requested).toEqual(['Fixture Sans'])
  release()
  await expect.poll(() => requested).toEqual(['Fixture Sans', 'Fixture Serif'])
  await expect(page.getByRole('listbox', { name: 'Font families' }).getByText('Fixture Serif', { exact: true })).toHaveCount(2)
  await expect(page.getByRole('combobox', { name: 'Font family', exact: true })).toContainText('Geist')
})

