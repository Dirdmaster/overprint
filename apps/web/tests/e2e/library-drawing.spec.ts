import { test, expect } from '@playwright/test'
import { demoBoard } from '../fixtures/demoBoard'
test('scaled linked text detaches and reopens with editable content and physical size', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await page.getByRole('button', { name: 'Draw text', exact: true }).click()
  const point = await page.locator('svg[role="img"]').evaluate(svg => {
    const p = new DOMPoint(28, 50).matrixTransform((svg.querySelector('g[transform]') as SVGGraphicsElement).getScreenCTM()!)
    return { x: p.x, y: p.y }
  })
  await page.mouse.click(point.x, point.y)
  await page.getByLabel('Text content').fill('Brand')
  await page.getByLabel('Text size (mm)').fill('4')
  await expect(page.getByText('Updating text…', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Library', exact: true }).click()
  await page.getByLabel('Composition name', { exact: true }).fill('Text composition')
  await page.getByRole('button', { name: 'Save selection', exact: true }).click()
  await page.getByRole('button', { name: 'Place linked Text composition', exact: true }).click()
  await page.getByRole('button', { name: 'Close library', exact: true }).click()
  const width = page.getByLabel('Artwork width', { exact: true })
  await width.fill(String(Number(await width.inputValue()) * 2))
  await width.press('Tab')
  await page.getByRole('button', { name: 'Detach instance', exact: true }).click()
  await expect(page.getByLabel('Text content')).toHaveValue('Brand')
  expect(Number(await page.getByLabel('Text size (mm)').inputValue())).toBeCloseTo(8, 1)
  const detachedWidth = Number(await width.inputValue())
  await page.getByLabel('Text fill').fill('#ff0000')
  await expect(page.getByText('Updating text…', { exact: true })).toHaveCount(0)
  expect(Number(await width.inputValue())).toBeCloseTo(detachedWidth, 1)
  await page.keyboard.press('Control+s')
  await expect(page.getByRole('status')).toContainText('All changes saved')
  await page.reload()
  await expect(page.locator('[data-artwork-layer] image')).toHaveCount(2)
  await page.getByRole('button', { name: 'Text', exact: true }).first().click()
  await expect(page.getByLabel('Text content')).toHaveValue('Brand')
  expect(Number(await page.getByLabel('Text size (mm)').inputValue())).toBeCloseTo(8, 1)
})
