test('restores the old IndexedDB autosave into the gallery', async ({ page }) => {
  await page.goto('/setup')
  await page.evaluate(async value => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => {
      const request = indexedDB.open('overprint', 1)
      request.onupgradeneeded = () => request.result.createObjectStore('projects')
      request.onsuccess = () => resolve(request.result)
      request.onerror = () => reject(request.error)
    })
    await new Promise<void>((resolve, reject) => { const tx = db.transaction('projects', 'readwrite'); tx.objectStore('projects').put(JSON.stringify(value), 'current'); tx.oncomplete = () => resolve(); tx.onabort = () => reject(tx.error) })
    db.close()
  }, legacyProject)
  await page.goto('/')
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await expect(page.getByRole('article')).toContainText('Legacy board')
})

