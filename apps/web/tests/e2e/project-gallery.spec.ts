import { test, expect } from '@playwright/test'
import { demoBoard } from '../fixtures/demoBoard'

test('projects can be duplicated, renamed, reopened and deleted independently', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  const gallery = page.getByRole('dialog', { name: 'Projects', exact: true })
  await expect(gallery.getByRole('article')).toHaveCount(1)
  await gallery.getByRole('button', { name: 'Duplicate' }).click()
  await expect(gallery.getByRole('article')).toHaveCount(2)
  const copy = gallery.getByRole('article').filter({ hasText: 'copy' })
  await copy.getByLabel('Project name').fill('Second design')
  await copy.getByRole('button', { name: 'Rename' }).click()
  await gallery.getByRole('article').filter({ hasText: 'Second design' }).getByRole('button', { name: 'Open', exact: true }).click()
  await expect(gallery).not.toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await expect(gallery.getByRole('article').filter({ hasText: 'Second design' })).toContainText('Current')
  await gallery.getByRole('article').filter({ hasText: 'Second design' }).getByRole('button', { name: 'Delete', exact: true }).click()
  await gallery.getByRole('button', { name: 'Confirm deletion' }).click()
  await expect(gallery.getByRole('article')).toHaveCount(1)
})

const legacyProject = { version: 1, board: { name: 'Legacy board', bounds: { x: 0, y: 0, width: 50, height: 50 }, outline: 'M0,0 L50,0 L50,50 L0,50 Z', holes: '', layers: {} }, artwork: [], side: 'front', silk: true, mask: '#202723', fabrication: false }

test('migrates a legacy localStorage project once and keeps the original', async ({ page }) => {
  await page.addInitScript(value => { if (!localStorage.getItem('seeded')) { localStorage.setItem('overprint-project-v1', JSON.stringify(value)); localStorage.setItem('seeded', 'true') } }, legacyProject)
  await page.goto('/')
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('article')).toContainText('Legacy board')
  await page.reload()
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  expect(await page.evaluate(() => localStorage.getItem('overprint-project-v1'))).toContain('Legacy board')
})

test('conflicting tabs preserve the newer saved project and allow a recovery copy', async ({ page, context }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await expect(page.getByRole('button', { name: 'Save project', exact: true })).toBeVisible()
  await page.keyboard.press('Control+s')
  await expect(page.getByRole('status')).toContainText('All changes saved')
  const other = await context.newPage()
  await other.goto('/')
  await expect(other.getByRole('button', { name: 'Save project', exact: true })).toBeVisible()
  await page.getByRole('status').click()
  await page.keyboard.press('Control+s')
  await expect(page.getByRole('status')).toContainText('All changes saved')
  await other.keyboard.press('Control+s')
  await expect(other.getByRole('status')).toContainText('changed in another tab')
  await other.getByRole('button', { name: 'Save recovery copy', exact: true }).click()
  await expect(other.getByRole('status')).toContainText('Recovery copy saved')
  await other.getByRole('button', { name: 'Projects', exact: true }).click()
  await expect(other.getByRole('article')).toHaveCount(2)
})

test('failed local writes stop a project switch and leave download recovery available', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('button', { name: 'Duplicate', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.evaluate(() => { IDBObjectStore.prototype.put = () => { throw new DOMException('Storage full', 'QuotaExceededError') } })
  await page.getByRole('article').filter({ hasText: 'copy' }).getByRole('button', { name: 'Open', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Projects', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Download recovery project' })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download recovery project' }).click()
  expect((await download).suggestedFilename()).toBe('Demo board.overprint')
})

test('new PCB keeps the former project while PCB update keeps artwork and identity', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
  await page.getByLabel('Choose board export').setInputFiles(demoBoard)
  await page.getByLabel('Choose SVG graphic').setInputFiles('tests/fixtures/class-paints.svg')
  for (const action of ['Update PCB, keep artwork', 'Open board']) {
    await page.getByLabel('More ways to open a board').click()
    await page.getByRole('button', { name: 'Import PCB', exact: true }).click()
    await page.getByLabel('Choose board export').setInputFiles('tests/fixtures/browser-import.kicad_pcb')
    await page.getByRole('button', { name: action, exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Open another board?' })).not.toBeVisible()
    await expect(page.locator('[data-artwork-layer] image')).toHaveCount(action.startsWith('Update') ? 1 : 0)
    await page.getByRole('button', { name: 'Projects', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(action.startsWith('Update') ? 1 : 2)
    await page.getByRole('button', { name: 'Close', exact: true }).click()
  }
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('article').filter({ hasText: 'Demo board' }).getByRole('button', { name: 'Open', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Projects', exact: true })).not.toBeVisible()
  await expect(page.locator('[data-artwork-layer] image')).toHaveCount(1)
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Projects', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/project-gallery-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'test-results/project-gallery-mobile.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})

